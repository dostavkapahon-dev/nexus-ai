"""
Понимание свободного текста: пишешь обычными словами — агент сам решает, что делать.

Сначала быстрые правила без LLM (ссылки, явные слова) — это бесплатно и мгновенно.
Если не распознали — дешёвая модель определяет намерение.

Возвращает команду вида "/viral <url>" или "/factory тема", которую бот выполняет.
"""
import re

URL_RE = re.compile(r"https?://\S+")

VIDEO_HOSTS = ("instagram.com", "tiktok.com", "youtube.com", "youtu.be", "vk.com")

# Быстрые правила: слово в тексте → команда (без вызова модели).
RULES = [
    (("проанализируй аккаунт", "разбери аккаунт", "анализ аккаунта",
      "что с моим инстаграм", "статистика аккаунта"), "/strategy"),
    (("автопилот", "полный цикл", "начни с нуля", "с чего начать"), "/auto"),
    (("план на неделю", "контент план", "что постить"), "/plan7"),
    (("тренды", "что сейчас популярно", "что залетает"), "/trend"),
    (("статус", "как дела у системы", "что работает"), "/diag"),
    (("опубликуй", "публикуй очередь"), "/publish"),
    (("пауза", "останови"), "/pause"),
    (("продолжи", "возобнови"), "/resume"),
]

# Слова, после которых человек ждёт ролик, а не рассказ о том, как его сделать.
# Глагол при этом не обязателен: «ИИ ролик» — такая же заявка, как «сделай рилс».
REEL_WORDS = ("ролик", "рилс", "reels", "reel", "shorts", "шортс", "клип", "видео")

INTENT_SYSTEM = (
    "Ты — маршрутизатор команд для SMM-агента. По сообщению пользователя определи, "
    "что он хочет, и верни ОДНУ команду из списка. Отвечай ТОЛЬКО командой, без пояснений.\n"
    "/auto — полный цикл: анализ, стратегия, ролик\n"
    "/strategy — разбор аккаунта и варианты стратегии\n"
    "/factory <тема> — создать ролик на тему\n"
    "/predict <идея> — оценить шанс залёта идеи\n"
    "/plan7 — контент-план на неделю\n"
    "/hunt <ниша> — найти залетевшие ролики\n"
    "/trend — тренды сейчас\n"
    "/diag — что подключено\n"
    "/do <задача> — сделать что-то в браузере на ПК\n"
    "/chat — просто ответить текстом, если это вопрос или разговор"
)


def quick_route(text: str) -> str | None:
    """Мгновенная маршрутизация без LLM. None — если не уверены."""
    t = (text or "").strip()
    low = t.lower()

    # Ссылка на видео → разбор референса; прочие ссылки → зрение.
    urls = URL_RE.findall(t)
    if urls:
        u = urls[0]
        if any(h in u for h in VIDEO_HOSTS):
            return f"/viral {' '.join(urls[:5])}"
        return f"/see {u}"

    for words, cmd in RULES:
        if any(w in low for w in words):
            return cmd

    # «Сделай ролик про X» / «нужен рилс о X» → фабрика с темой
    m = re.search(r"(?:сделай|создай|сгенерируй|нужен|хочу)\s+(?:рилс\w*|reels|ролик|видео)\s*(?:про|о|об)?\s*(.*)",
                  t, re.IGNORECASE)
    if m:
        topic = m.group(1).strip(" .!?")  # регистр исходного текста сохраняем
        return f"/factory {topic}" if topic else "/factory"

    # Короткая заявка без глагола: «ИИ ролик», «нужен reels», «видео про доставку».
    # Остаток фразы после слова-маркера — это и есть тема.
    for w in REEL_WORDS:
        if re.search(rf"(?<!\w){w}", low):
            rest = re.sub(rf"(?<!\w){w}\w*", " ", t, flags=re.IGNORECASE)
            rest = re.sub(r"^\s*(?:про|о|об|на тему)\s+", "", rest.strip(" .,!?—-"),
                          flags=re.IGNORECASE).strip(" .,!?—-")
            return f"/factory {rest}" if len(rest) > 2 else "/factory"
    return None


async def route(text: str, history: str = "") -> str:
    """Определяет команду для свободного текста (правила → дешёвая модель).

    История нужна для коротких ответов: «1» или «Напиши» сами по себе ничего не
    значат — смысл им придаёт предыдущая реплика бота.
    """
    quick = quick_route(text)
    if quick:
        return quick
    # Без ключей уточнять намерение нечем — отвечаем разговором, а тот при
    # необходимости отдаст вопрос Клоду.
    from core.ai_router import ai_available
    if not ai_available():
        return "/chat"
    try:
        from core.ai_router import ai_router, ECONOMY_MODELS
        model = ECONOMY_MODELS.get("adapter", "gemini-2.0-flash")
        prompt = (f"Предыдущий разговор:\n{history}\n\nНовое сообщение: {text[:800]}"
                  if history else text[:800])
        res = await ai_router.call(model, INTENT_SYSTEM, prompt)
        out = (res.get("text") or "").strip().split("\n")[0].strip()
        if out.startswith("/"):
            return out
    except Exception:
        pass
    return "/chat"


CHAT_SYSTEM = (
    "Ты — ассистент SMM-агента NEXUS AI. Отвечай кратко, по-русски, по делу.\n"
    "ГЛАВНОЕ ПРАВИЛО: ты только говоришь, работу выполняет система по команде. "
    "Поэтому НИКОГДА не обещай действие от первого лица — ни «сейчас сгенерирую», "
    "ни «смонтирую», ни «опубликую», ни «начинаю». Такое обещание никто не "
    "исполнит, и человек останется ждать впустую.\n"
    "Если человек хочет ролик — не расписывай план работ, а задай ОДИН вопрос: "
    "какая тема. Если он хочет что-то другое из умений системы (анализ аккаунта, "
    "тренды, разбор чужого ролика, контент-план, публикация) — назови команду, "
    "которую надо отправить, например /trend или /strategy."
)

# Что отвечаем, когда модель вернула пустоту. Раньше пустая строка уходила в
# Telegram, тот отвечал «message text is empty», и для человека это выглядело
# как молчание бота.
EMPTY_REPLY = (
    "🤔 Не понял запрос. Скажите словами, что нужно, например:\n"
    "• «ролик про доставку еды» — сделаю ролик\n"
    "• «тренды» — что сейчас залетает\n"
    "• «разбери аккаунт» — анализ и стратегия\n"
    "• /help — все команды"
)


NO_AI_REPLY = (
    "🤖 Ни один ИИ-провайдер не подключён, поэтому свободные команды словами "
    "сейчас недоступны.\n\n"
    "<b>Что работает без ИИ прямо сейчас:</b>\n"
    "/queue — очередь публикаций и повторы\n"
    "/tasks — задачи и их статусы\n"
    "/errors — что сломалось за сутки\n"
    "/cost — расходы и бюджет\n"
    "/diag — что подключено\n"
    "/rivals — метрики конкурентов\n\n"
)


async def chat_reply(text: str, history: str = "") -> str:
    """Свободный ответ, когда это просто вопрос/разговор.

    Без единого ключа отвечаем понятным текстом со списком рабочих команд:
    «All AI providers failed» ничего не говорит о том, что делать дальше.
    """
    from core.ai_router import ai_available, FREE_SIGNUP_HINT
    if not ai_available():
        # Ключей нет — но вопрос не пропадает: его получит Клод. Подсказку про
        # бесплатный ключ оставляем: это по-прежнему самый быстрый способ
        # избавиться от ожидания.
        from core import ai_escrow
        if ai_escrow.wanted():
            answer = await ai_escrow.ask(CHAT_SYSTEM, text, role="chat",
                                         errors="нет ни одного ключа ИИ")
            return f"{answer}\n\n{FREE_SIGNUP_HINT}"
        return NO_AI_REPLY + FREE_SIGNUP_HINT

    try:
        from core.ai_router import ai_router, ECONOMY_MODELS
        model = ECONOMY_MODELS.get("copywriter", "gemini-2.0-flash")
        prompt = (f"Предыдущий разговор:\n{history}\n\nНовое сообщение: {text[:1500]}"
                  if history else text[:1500])
        res = await ai_router.call(model, CHAT_SYSTEM, prompt)
        return (res.get("text") or "").strip()[:3000] or EMPTY_REPLY
    except Exception as e:
        return f"⚠️ Не смог ответить: {str(e)[:150]}"
